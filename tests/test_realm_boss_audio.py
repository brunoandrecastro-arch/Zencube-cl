"""Regressions for twelve exclusive Realm Chronicles boss themes.
The 12 original OGG files are supplied by the game author, not generated by CI.
The loader must remain non-breaking until the actual binaries are installed.
Once any boss audio is added, all twelve must be present and match their SHA256.
"""
from pathlib import Path
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
AUDIO = ROOT / "assets" / "realm_boss_music"
IDS = [
    "mist_guardian", "mirror_novice", "veil_monk",
    "ash_runner", "banner_guardian", "ember_high_priest",
    "wind_scribe", "bridge_sentinel", "sky_archivist",
    "lotus_witness", "halo_keeper", "fully_aware",
]
CHECKSUMS = AUDIO / "checksums.sha256"

def test():
    loader = (ROOT / "core" / "ZenRealmBossMusic.gd").read_text()
    controller = (ROOT / "ui" / "AscendController.gd").read_text()
    assert len(IDS) == 12 and len(set(IDS)) == 12
    for boss_id in IDS:
        assert f'"{boss_id}"' in loader, f"Missing boss ID {boss_id}"
    assert 'stream.loop = true' in loader
    assert 'if not ResourceLoader.exists(path): return null' in loader
    assert 'if realm_story_active:' in controller
    assert 'BossMusic.stream_for(realm_story_stage)' in controller
    assert 'if battle_theme != null: return battle_theme' in controller
    assert 'if not bool(data.settings.get("music", false)):' in controller
    assert 'sync_realm_music()' in controller

    rows = [r.split() for r in CHECKSUMS.read_text().splitlines() if r.strip()]
    expected = {filename: checksum for checksum, filename in rows}
    assert set(expected) == {f"{name}.ogg" for name in IDS}, "Checksum manifest must contain exactly 12 boss loops."
    available = {p.name for p in AUDIO.glob("*.ogg")}
    if not available:
        print("PENDING: original 12 user-supplied OGG binaries are not yet uploaded to the GitHub branch; game safely uses Realm music.")
        return
    assert available == set(expected), f"Partial or misnamed boss music upload: missing={set(expected)-available}, unexpected={available-set(expected)}"
    for filename, checksum in expected.items():
        data = (AUDIO / filename).read_bytes()
        assert len(data) > 150000 and data.startswith(b"OggS"), f"Invalid OGG audio: {filename}"
        assert hashlib.sha256(data).hexdigest() == checksum, f"User-original audio differs: {filename}"
    print("PASS: all 12 original OGG Boss themes are present and match user's SHA256 manifest.")

if __name__ == "__main__":
    test()
